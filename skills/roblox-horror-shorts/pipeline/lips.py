"""Lip-sync data from a voice clip -> roblox/src/Lips.lua (ReplicatedStorage.Lips), read by Kit.clientFaces.

usage (from the work folder): python3 <skill>/pipeline/lips.py <clip_name> <audio file> [start_s end_s]
Adds/replaces one clip; other clips in Lips.lua are kept. Per 1/30 s frame:
  v = mouth openness 0..1 (loudness), s = 0 rounded ("oo") .. 1 stretched ("ee") (spectral centroid).
"""
import json, os, re, subprocess, sys
import numpy as np

FPS = 30
SR = 16000
OUT = os.path.join(os.environ.get("SHORTS_ROOT", "."), "roblox", "src", "Lips.lua")  # run from the work folder


def load(path, a=None, b=None):
    cmd = ["ffmpeg", "-loglevel", "error"]
    if a is not None:
        cmd += ["-ss", str(a), "-t", str(b - a)]
    cmd += ["-i", path, "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"]
    return np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, np.int16).astype(np.float32) / 32768


def analyse(x):
    hop = SR // FPS
    n = len(x) // hop
    fr = x[: n * hop].reshape(n, hop)
    rms = np.sqrt((fr ** 2).mean(1))
    ref = np.percentile(rms, 95) or 1.0
    v = np.clip(rms / ref, 0, 1) ** 0.8
    # fast open, slower close (mouths don't snap shut between syllables)
    for i in range(1, n):
        v[i] = max(v[i], v[i - 1] * 0.6)
    v[v < 0.08] = 0  # silence = closed mouth
    spec = np.abs(np.fft.rfft(fr * np.hanning(hop), axis=1))
    freqs = np.fft.rfftfreq(hop, 1 / SR)
    cen = (spec * freqs).sum(1) / (spec.sum(1) + 1e-9)
    s = np.clip((cen - 600) / 2400, 0, 1)
    return [round(float(a), 2) for a in v], [round(float(a), 2) for a in s]


def read_clips():
    if not os.path.exists(OUT):
        return {}
    m = re.search(r"--DATA (.*)$", open(OUT).read(), re.M)
    return json.loads(m.group(1)) if m else {}


def write(clips):
    lua = ["-- generated by pipeline/lips.py: lip-sync envelopes (see Kit.clientFaces). Do not edit by hand.", "return {"]
    for k, c in clips.items():
        lua.append(f'\t["{k}"] = {{fps = {FPS}, v = {{{",".join(map(str, c["v"]))}}}, s = {{{",".join(map(str, c["s"]))}}}}},')
    lua.append("}")
    lua.append("--DATA " + json.dumps(clips, separators=(",", ":")))
    open(OUT, "w").write("\n".join(lua) + "\n")


if __name__ == "__main__":
    name, path = sys.argv[1], sys.argv[2]
    a, b = (float(sys.argv[3]), float(sys.argv[4])) if len(sys.argv) > 4 else (None, None)
    v, s = analyse(load(path, a, b))
    assert len(v) == len(s) and max(v) > 0.5, "no speech found"
    clips = read_clips()
    clips[name] = {"v": v, "s": s}
    write(clips)
    print(f"{name}: {len(v)} frames ({len(v) / FPS:.2f} s), open {sum(x > 0 for x in v) / len(v):.0%} of the time -> {os.path.relpath(OUT)}")
