"""shots.json + events.json + words_full.json + script.txt -> Timeline.lua (shots, ~1.2 s beats, events) + beats.json.
Run in a project folder after timeline.py:   python3 make_timeline_lua.py
Beats: each script line is cut into shots of about TARGET seconds, preferring cuts right after , . ? ! ... (top Shorts
cuts every ~1.2 s). Agents then give each beat its own camera."""
import json, re
from pathlib import Path

TARGET, MIN_BEAT, MAX_BEAT = 1.05, 0.7, 1.5  # top Shorts cut every 1.15-1.5 s
HERE = Path.cwd()
shots = json.loads((HERE / "shots.json").read_text())
ev = json.loads((HERE / "events.json").read_text())
words = json.loads((HERE / "words_full.json").read_text())  # {line: [[word, t_full], ...]}
lines = [l.replace("*", "").strip() for l in (HERE / "script.txt").read_text().splitlines() if l.strip()]


def cuts_for(s):
    """Times (full timeline) where this line's shot is cut into beats."""
    start, stop = s["start"], s["end"]
    ws = words.get(str(s["line"]), [])
    script_ws = lines[s["line"] - 1].split()
    punct = [bool(re.search(r"[,.?!…—:;]\"?$", w)) for w in script_ws] if len(script_ws) == len(ws) else [False] * len(ws)
    cuts, last = [], start
    for i in range(1, len(ws)):
        t = ws[i][1] - 0.05  # cut just before the next word starts
        since, left = t - last, stop - t
        if left < MIN_BEAT:
            break
        if (punct[i - 1] and since >= MIN_BEAT) or since >= MAX_BEAT or (since >= TARGET and not any(punct[i:])):
            cuts.append(round(t, 3)); last = t
    return cuts


beats = []
for s in shots:
    edges = [s["start"]] + cuts_for(s) + [s["end"]]
    ws = words.get(str(s["line"]), [])
    for k in range(len(edges) - 1):
        a, b = edges[k], edges[k + 1]
        said = " ".join(w for w, t in ws if a - 0.05 <= t < b - 0.05)
        beats.append({"line": s["line"], "k": k + 1, "start": round(a, 3), "stop": round(b, 3), "words": said})
(HERE / "beats.json").write_text(json.dumps(beats, indent=1))

o = ["-- generated by make_timeline_lua.py (do not edit by hand)", "local T = {}", "T.FPS = 30", f"T.END = {shots[-1]['end']}", "T.shots = {"]
for s in shots:
    a = s["start"] + s["lead"]; b = a + (s["say"][1] - s["say"][0])
    o.append(f"\t{{line = {s['line']}, start = {s['start']}, stop = {s['end']}, sayStart = {round(a, 3)}, sayEnd = {round(b, 3)}, text = {json.dumps(lines[s['line'] - 1])}}},")
o.append("}")
o.append("-- beats: the camera cuts on these (k = beat number inside the line)")
o.append("T.beats = {")
for x in beats:
    o.append(f"\t{{line = {x['line']}, k = {x['k']}, start = {x['start']}, stop = {x['stop']}, words = {json.dumps(x['words'])}}},")
o.append("}")
o.append("-- every synced sound beat with its sound, in time order (the camera holds still before scares and snap-zooms on them)")
o.append("T.evs = {")
for e in sorted(ev, key=lambda e: e["frame"]):
    o.append(f"\t{{id = {json.dumps(e['id'])}, t = {round((e['frame'] - 1) / 30, 3)}, sound = {json.dumps(e['sound'] or '')}}},")
o.append("}")
o.append("T.ev = {")
for e in ev:
    o.append(f"\t{e['id']} = {round((e['frame'] - 1) / 30, 3)},")
o += ["}", "return T"]
(HERE / "Timeline.lua").write_text("\n".join(o) + "\n")
L = [x["stop"] - x["start"] for x in beats]
print(f"{len(shots)} lines -> {len(beats)} beats, avg {sum(L) / len(L):.2f}s, max {max(L):.2f}s")
